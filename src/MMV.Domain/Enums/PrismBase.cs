namespace MMV.Domain.Enums;

/// <summary>
/// Représente l'orientation de la base d'un prisme optique.
/// </summary>
public enum PrismBase
{
    /// <summary>
    /// Base orientée vers l'intérieur (nasale).
    /// </summary>
    In,

    /// <summary>
    /// Base orientée vers l'extérieur (temporale).
    /// </summary>
    Out,

    /// <summary>
    /// Base orientée vers le haut (supérieure).
    /// </summary>
    Up,

    /// <summary>
    /// Base orientée vers le bas (inférieure).
    /// </summary>
    Down
}
