    /// <summary>
    /// B0.7 — Reproduit la forme EXACTE du chemin <c>CreateProductUseCase</c> /
    /// <c>UpdateProductUseCase</c> : une écriture échoue dans le vrai
    /// <see cref="EfTransactionRunner"/>, la transaction est annulée, puis le catch de production
    /// réinterroge la base avec <c>ExistsFreshAsync</c> — SUR LE MÊME <see cref="OpticDbContext"/>.
    ///
    /// <para>
    /// Code de production réellement exécuté : <see cref="OpticDbContext"/>,
    /// <see cref="EfTransactionRunner"/>, <see cref="PersistenceErrorMapper"/>,
    /// <c>SupplierRepository.ExistsFreshAsync</c>, et le chemin EF <c>DbSet.Add</c> +
    /// <c>SaveChangesAsync</c> du modèle de production.
    /// </para>
    ///
    /// <para>
    /// LIMITE EXPLICITE : la table <c>"Suppliers"</c> est créée À LA MAIN par le harness, et la
    /// contrainte d'unicité sur <c>"Name"</c> est un INSTRUMENT DE MESURE qui n'existe pas dans le
    /// modèle MMV. Aucun schéma de production n'est revendiqué, aucune migration n'est produite :
    /// la portabilité du schéma reste entièrement à faire en P4-5.
    /// </para>
    /// </summary>
    [SkippableFact]
    public async Task B07_change_tracker_and_exists_fresh_after_failed_save_changes()
    {
        Skip.IfNot(SpikeEnvironment.IsConfigured(Provider), SpikeEnvironment.SkipReason(Provider));

        await using var database = await SpikeDatabase.CreateAsync(Provider, "e21b07");
        SpikeLog.Section(Experiment, Name,
            "B0.7 — ChangeTracker + ExistsFreshAsync apres SaveChanges echoue (chemin CreateProduct/UpdateProduct)");

        // Table du HARNESS, alignée sur le mapping EF de Supplier. Instrument de mesure, pas un schéma.
        await ExecuteOutsideTransactionAsync(database,
            "CREATE TABLE \"Suppliers\" (" +
            "\"SupplierId\" bigint GENERATED BY DEFAULT AS IDENTITY CONSTRAINT \"PK_Suppliers\" PRIMARY KEY, " +
            "\"Name\" character varying(200) NOT NULL CONSTRAINT ux_harness_supplier_name UNIQUE, " +
            "\"ContactEmail\" character varying(254), " +
            "\"Phone\" character varying(20), " +
            "\"Address\" character varying(500), " +
            "\"ReferenceCode\" character varying(50));");

        // Identifiant semé VOLONTAIREMENT hors de portée immédiate de la séquence d'identité : sans
        // cela, l'INSERT d'EF entrerait en collision sur la CLÉ PRIMAIRE et l'on mesurerait un
        // accident de harness au lieu de la contrainte d'unicité visée.
        const long SeededSupplierId = 100_000L;

        await ExecuteOutsideTransactionAsync(database,
            $"INSERT INTO \"Suppliers\" (\"SupplierId\", \"Name\") VALUES ({SeededSupplierId}, 'FOURNISSEUR-EXISTANT');");

        var recorder = new CommandRecorder();
        await using var context = CreateProductionContext(database, recorder);

        var runner = new EfTransactionRunner(context);              // *** PRODUCTION ***
        var supplierRepository = new SupplierRepository(context);   // *** PRODUCTION ***

        var duplicate = new Supplier { Name = "FOURNISSEUR-EXISTANT" };

        recorder.Start("callback");

        var thrown = await CaptureAsync(() => runner.RunAsync(async ct =>
        {
            // Forme du use case : lecture fraîche DANS la transaction (production).
            var exists = await supplierRepository.ExistsFreshAsync(SeededSupplierId, ct);
            Assert.True(exists);

            // Puis une écriture qui échoue réellement côté serveur.
            context.Suppliers.Add(duplicate);
            await context.SaveChangesAsync(ct);
        }, CancellationToken.None));

        recorder.Stop();

        // --- Chaîne complète EF -> mapper --------------------------------------------------------
        Assert.NotNull(thrown);
        var shape = ExceptionShape.Capture(thrown!);
        SpikeLog.Write(Experiment, Name, $"B0.7 exception sortie du runner | {shape.ToEvidenceLine()}");

        var mapped = Assert.IsType<PersistenceException>(thrown);
        Assert.Equal(PersistenceErrorCategory.UniqueConstraint, mapped.Category);

        var hasDbUpdate = shape.Frames.Any(f => typeof(DbUpdateException).IsAssignableFrom(f.ClrType));
        SpikeLog.Write(Experiment, Name,
            $"B0.7 mapping via SaveChangesAsync | Category={mapped.Category} | SqlState={shape.SqlState} " +
            $"| DbUpdateException presente={(hasDbUpdate ? "OUI" : "NON")}");

        // --- NIVEAU B : état du ChangeTracker APRÈS le rollback ----------------------------------
        var stateAfterRollback = context.Entry(duplicate).State;
        var pendingEntries = context.ChangeTracker.Entries()
            .Count(e => e.State is EntityState.Added or EntityState.Modified or EntityState.Deleted);

        SpikeLog.Write(Experiment, Name,
            $"B0.7 ChangeTracker apres rollback | Entry(duplicate).State={stateAfterRollback} " +
            $"| entrees en attente={pendingEntries} " +
            $"| CurrentTransaction={(context.Database.CurrentTransaction is null ? "null" : "PRESENTE")}");

        Assert.Null(context.Database.CurrentTransaction);

        // --- Le catch de production : ExistsFreshAsync sur le MÊME contexte ----------------------
        recorder.Start("catch");
        var stillExists = await supplierRepository.ExistsFreshAsync(SeededSupplierId, CancellationToken.None);
        recorder.Stop();

        Assert.True(stillExists);

        var catchCommands = recorder.Describe("catch");
        var catchWrites = recorder.WriteCommands("catch");

        SpikeLog.Write(Experiment, Name,
            $"B0.7 ExistsFreshAsync APRES rollback | executee=OUI (aucun 25P02) | resultat={stillExists} " +
            $"| commandes emises={catchCommands} | commandes d'ECRITURE={catchWrites.Count}");

        // Le point critique : la requête du catch ne doit RIEN réécrire, malgré une entité Added.
        Assert.Empty(catchWrites);

        // Et le résultat doit venir de la BASE : l'entité en doublon ne doit pas avoir été persistée.
        var persistedDuplicates = await CountSuppliersNamedAsync(database, "FOURNISSEUR-EXISTANT");
        Assert.Equal(1L, persistedDuplicates);
        SpikeLog.Write(Experiment, Name,
            $"B0.7 donnees apres rollback | lignes 'FOURNISSEUR-EXISTANT' = {persistedDuplicates} " +
            "(la ligne semee, aucune ecriture partielle).");
    }

