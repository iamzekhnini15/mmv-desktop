    private static OpticDbContext CreateProductionContext(SpikeDatabase database, CommandRecorder? recorder)
    {
        var builder = new DbContextOptionsBuilder<OpticDbContext>().UseNpgsql(database.ConnectionString);

        if (recorder is not null)
        {
            builder.AddInterceptors(recorder);
        }

        return new OpticDbContext(builder.Options);
    }

    private static async Task ExecuteOutsideTransactionAsync(SpikeDatabase database, string sql)
    {
        await using var connection = await database.OpenRawAsync();
        await using var command = connection.CreateCommand();
        command.CommandText = sql;
        await command.ExecuteNonQueryAsync();
    }

    private static async Task ExecuteAsync(DbConnection connection, DbTransaction transaction, string sql)
    {
        await using var command = connection.CreateCommand();
        command.Transaction = transaction;
        command.CommandText = sql;
        await command.ExecuteNonQueryAsync();
    }

