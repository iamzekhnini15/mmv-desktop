    /// <summary>
    /// B0.5 — <see cref="UnitOfWork"/> n'a AUCUN appelant de production pour
    /// <c>BeginTransactionAsync</c> / <c>CommitAsync</c> / <c>RollbackAsync</c> (vérifié
    /// statiquement). On mesure néanmoins son comportement RÉEL, car son catch relaie le jeton
    /// CLIENT au rollback là où <see cref="EfTransactionRunner"/> utilise
    /// <c>CancellationToken.None</c>.
    ///
    /// <para>
    /// La mesure procède en deux temps : d'abord les PRIMITIVES (que fait Npgsql/EF quand on
    /// commit/rollback avec un jeton déjà annulé ?), puis le COMPOSITE (le vrai
    /// <c>UnitOfWork.CommitAsync</c>).
    /// </para>
    /// </summary>
    [SkippableFact]
    public async Task B05_unit_of_work_rollback_with_already_cancelled_token()
    {
        Skip.IfNot(SpikeEnvironment.IsConfigured(Provider), SpikeEnvironment.SkipReason(Provider));

        await using var database = await SpikeDatabase.CreateAsync(Provider, "e21b05");
        SpikeLog.Section(Experiment, Name, "B0.5 — UnitOfWork : rollback avec jeton client DEJA annule");

        await ExecuteOutsideTransactionAsync(database, CreateProbeTable);

        // --- PRIMITIVE 1 : CommitAsync(jeton annulé) --------------------------------------------
        Exception? commitFailure;
        await using (var context = CreateProductionContext(database, recorder: null))
        {
            await using var transaction = await context.Database.BeginTransactionAsync();
            await context.Database.ExecuteSqlRawAsync("INSERT INTO p4_tx_probe (code) VALUES ('P1');");

            using var cts = new CancellationTokenSource();
            cts.Cancel();

            commitFailure = await CaptureAsync(() => transaction.CommitAsync(cts.Token));
            SpikeLog.Write(Experiment, Name,
                "B0.5 primitive CommitAsync(jeton annule) | " +
                (commitFailure is null
                    ? "AUCUNE exception (le commit a abouti)"
                    : ExceptionShape.Capture(commitFailure).ToEvidenceLine()));
        }

        var persistedP1 = await CountProbeAsync(database, "P1");
        SpikeLog.Write(Experiment, Name,
            $"B0.5 primitive CommitAsync | lignes 'P1' persistees apres liberation du contexte = {persistedP1}");

        // --- PRIMITIVE 2 : RollbackAsync(jeton annulé) sur une transaction vivante ---------------
        // QUESTION DÉCISIVE : si l'appel LÈVE, le rollback a-t-il tout de même eu lieu, ou la
        // transaction reste-t-elle OUVERTE ? On l'observe DEPUIS LA MÊME session, avant toute
        // libération : une transaction encore ouverte voit ses propres écritures non validées.
        Exception? rollbackFailure;
        await using (var context = CreateProductionContext(database, recorder: null))
        {
            await using var transaction = await context.Database.BeginTransactionAsync();
            await context.Database.ExecuteSqlRawAsync("INSERT INTO p4_tx_probe (code) VALUES ('P2');");

            using var cts = new CancellationTokenSource();
            cts.Cancel();

            rollbackFailure = await CaptureAsync(() => transaction.RollbackAsync(cts.Token));
            SpikeLog.Write(Experiment, Name,
                "B0.5 primitive RollbackAsync(jeton annule) | " +
                (rollbackFailure is null
                    ? "AUCUNE exception (le rollback a abouti)"
                    : ExceptionShape.Capture(rollbackFailure).ToEvidenceLine()));

            var transactionStillOpen = context.Database.CurrentTransaction is not null;

            // Lecture DANS la session du test. Si la transaction a bien été annulée, la ligne a
            // disparu ; si elle est encore ouverte, la session voit toujours sa propre écriture.
            var visibleInSession = await CaptureScalarAsync(context,
                "SELECT count(*)::bigint AS \"Value\" FROM p4_tx_probe WHERE code = 'P2'");

            SpikeLog.Write(Experiment, Name,
                $"B0.5 primitive RollbackAsync — ETAT APRES L'EXCEPTION | CurrentTransaction=" +
                $"{(transactionStillOpen ? "ENCORE PRESENTE" : "null")} | lignes 'P2' vues par la MEME session=" +
                $"{visibleInSession?.ToString() ?? "(lecture refusee)"} " +
                "(>0 => le ROLLBACK N'A PAS EU LIEU, la transaction est restee OUVERTE)");

            // Rollback de rattrapage avec CancellationToken.None : exactement ce que fait
            // EfTransactionRunner.SafeRollbackAsync. Doit aboutir.
            var retry = await CaptureAsync(() => transaction.RollbackAsync(CancellationToken.None));
            SpikeLog.Write(Experiment, Name,
                "B0.5 primitive RollbackAsync(CancellationToken.None) de rattrapage | " +
                (retry is null ? "ABOUTI" : ExceptionShape.Capture(retry).ToEvidenceLine()));
        }

        var persistedP2 = await CountProbeAsync(database, "P2");
        SpikeLog.Write(Experiment, Name,
            $"B0.5 primitive RollbackAsync | lignes 'P2' persistees apres liberation du contexte = {persistedP2}");

        // --- COMPOSITE : le VRAI UnitOfWork ------------------------------------------------------
        Exception? unitOfWorkFailure;
        var context3 = CreateProductionContext(database, recorder: null);
        var unitOfWork = new UnitOfWork(context3); // *** CODE DE PRODUCTION ***
        try
        {
            await unitOfWork.BeginTransactionAsync();
            await context3.Database.ExecuteSqlRawAsync("INSERT INTO p4_tx_probe (code) VALUES ('U');");

            using var cts = new CancellationTokenSource();
            cts.Cancel();

            unitOfWorkFailure = await CaptureAsync(() => unitOfWork.CommitAsync(cts.Token));

            // ÉTAT AVANT toute libération : le catch de CommitAsync a-t-il réellement annulé ?
            var stillOpen = context3.Database.CurrentTransaction is not null;
            var visibleInSession = await CaptureScalarAsync(context3,
                "SELECT count(*)::bigint AS \"Value\" FROM p4_tx_probe WHERE code = 'U'");

            SpikeLog.Write(Experiment, Name,
                $"B0.5 composite — ETAT AVANT LIBERATION | CurrentTransaction=" +
                $"{(stillOpen ? "ENCORE PRESENTE" : "null")} | lignes 'U' vues par la MEME session=" +
                $"{visibleInSession?.ToString() ?? "(lecture refusee)"} " +
                "(>0 => le catch de UnitOfWork.CommitAsync n'a PAS annule ; seule la liberation le fera)");
        }
        finally
        {
            await unitOfWork.DisposeAsync();
        }

        var unitOfWorkShape = unitOfWorkFailure is null ? null : ExceptionShape.Capture(unitOfWorkFailure);
        SpikeLog.Write(Experiment, Name,
            "B0.5 composite UnitOfWork.CommitAsync(jeton annule) | " +
            (unitOfWorkShape?.ToEvidenceLine() ?? "AUCUNE exception (le commit a abouti)"));

        var persistedU = await CountProbeAsync(database, "U");
        SpikeLog.Write(Experiment, Name,
            $"B0.5 composite | lignes 'U' persistees apres liberation = {persistedU} " +
            "(0 = aucune ecriture partielle conservee ; >0 = commit effectif malgre le jeton annule)");

        // Faits consignés, pas de correction ici : la décision appartient à P4-4B1.
        SpikeLog.Write(Experiment, Name,
            "B0.5 CONSTAT STATIQUE (invariant) : EfTransactionRunner.SafeRollbackAsync utilise " +
            "CancellationToken.None ; UnitOfWork.RollbackTransactionAsync relaie le jeton CLIENT.");

        // Le test MESURE : il ne doit pas échouer sur un comportement observé. Seule l'absence totale
        // d'observation serait un échec.
        Assert.True(persistedP1 >= 0 && persistedP2 >= 0 && persistedU >= 0,
            "B0.5 : aucune observation n'a pu etre relevee.");
    }

