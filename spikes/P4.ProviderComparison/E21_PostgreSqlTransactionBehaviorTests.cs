    /// <summary>
    /// B0.2 — Le VRAI <see cref="EfTransactionRunner"/> de production, construit sur le VRAI
    /// <see cref="OpticDbContext"/> configuré Npgsql, exécuté tel quel.
    ///
    /// <para>
    /// Le schéma de production n'est PAS créé : le callback n'utilise que la table de sonde du
    /// harness. C'est suffisant et volontaire — le runner ne touche jamais au modèle, il n'utilise
    /// que <c>Database.CurrentTransaction</c>, <c>BeginTransactionAsync</c>, <c>CommitAsync</c> et
    /// <c>RollbackAsync</c>. La frontière transactionnelle mesurée est donc EXACTEMENT celle de la
    /// production.
    /// </para>
    ///
    /// <para>B0.4 est mesuré dans le même test par un intercepteur du HARNESS.</para>
    /// </summary>
    [SkippableFact]
    public async Task B02_real_transaction_runner_rolls_back_and_maps_unique_violation()
    {
        Skip.IfNot(SpikeEnvironment.IsConfigured(Provider), SpikeEnvironment.SkipReason(Provider));

        await using var database = await SpikeDatabase.CreateAsync(Provider, "e21b02");
        SpikeLog.Section(Experiment, Name, "B0.2 — VRAI EfTransactionRunner de production sur PostgreSQL");

        await ExecuteOutsideTransactionAsync(database, CreateProbeTable);

        var recorder = new CommandRecorder();
        await using var context = CreateProductionContext(database, recorder);

        // *** CODE DE PRODUCTION, INSTANCIÉ TEL QUEL ***
        var runner = new EfTransactionRunner(context);

        recorder.Start("callback");

        var thrown = await CaptureAsync(() => runner.RunAsync(async ct =>
        {
            await context.Database.ExecuteSqlRawAsync("INSERT INTO p4_tx_probe (code) VALUES ('B');", ct);
            await context.Database.ExecuteSqlRawAsync("INSERT INTO p4_tx_probe (code) VALUES ('B');", ct);
        }, CancellationToken.None));

        recorder.Stop();

        // --- 1) Exception finale reçue par l'appelant -------------------------------------------
        Assert.NotNull(thrown);
        var shape = ExceptionShape.Capture(thrown!);
        SpikeLog.Write(Experiment, Name, $"B0.2 exception sortie du runner | {shape.ToEvidenceLine()}");

        var mapped = Assert.IsType<PersistenceException>(thrown);
        Assert.Equal(PersistenceErrorCategory.UniqueConstraint, mapped.Category);
        Assert.Equal("23505", shape.SqlState);
        Assert.True(shape.HasPostgresException,
            "B0.2 : la PostgresException d'origine doit rester accessible en InnerException.");
        SpikeLog.Write(Experiment, Name,
            $"B0.2 mapping | type={mapped.GetType().FullName} | Category={mapped.Category} " +
            $"| SqlState conserve={shape.SqlState} | contrainte={shape.ConstraintName ?? "(aucune)"}");

        // --- 2) L'écriture #1 a-t-elle été annulée elle aussi ? ----------------------------------
        var remaining = await CountProbeAsync(database, "B");
        Assert.Equal(0L, remaining);
        SpikeLog.Write(Experiment, Name,
            $"B0.2 donnees apres sortie du runner | lignes code='B' persistees={remaining} " +
            "=> INSERT #1 rollbacke avec la transaction.");

        // --- 3) Le MÊME DbContext est-il réutilisable après le rollback ? ------------------------
        Assert.Null(context.Database.CurrentTransaction);

        var reuse = await context.Database
            .SqlQueryRaw<long>("SELECT count(*)::bigint AS \"Value\" FROM p4_tx_probe")
            .SingleAsync();

        Assert.Equal(0L, reuse);
        SpikeLog.Write(Experiment, Name,
            "B0.2 reutilisation du MEME DbContext apres rollback | requete acceptee=OUI (aucun 25P02) " +
            $"| CurrentTransaction=null | lignes={reuse}");

        // --- 4) B0.4 : commandes applicatives exécutées APRÈS l'erreur, dans la transaction ------
        var afterFailure = recorder.CommandsAfterFirstFailure("callback");
        Assert.Empty(afterFailure);
        SpikeLog.Write(Experiment, Name,
            $"B0.4 commandes applicatives APRES l'echec, dans la transaction = {afterFailure.Count} " +
            $"| sequence complete du callback : {recorder.Describe("callback")}");
        SpikeLog.Write(Experiment, Name,
            "B0.4 LIMITE ASSUMEE : BEGIN/COMMIT/ROLLBACK passent par l'API ADO.NET de transaction, " +
            "PAS par DbCommand — un DbCommandInterceptor ne peut pas les voir. Aucune pretention contraire.");
    }

