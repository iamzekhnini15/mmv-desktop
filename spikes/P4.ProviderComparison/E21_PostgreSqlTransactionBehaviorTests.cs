    /// <summary>
    /// B0.1 — Sans ce contrôle, un test qui « ne voit pas de 25P02 » ne prouverait rien : il pourrait
    /// simplement être aveugle. On provoque donc délibérément l'état que la production doit éviter.
    /// Niveau : EXECUTED_SPIKE (SQL brut, aucun code MMV).
    /// </summary>
    [SkippableFact]
    public async Task B01_aborted_transaction_really_yields_25P02()
    {
        Skip.IfNot(SpikeEnvironment.IsConfigured(Provider), SpikeEnvironment.SkipReason(Provider));

        await using var database = await SpikeDatabase.CreateAsync(Provider, "e21b01");
        SpikeLog.Section(Experiment, Name, "B0.1 — CONTROLE POSITIF 25P02 (SQL brut, aucun code MMV)");

        await ExecuteOutsideTransactionAsync(database, CreateProbeTable);

        await using var connection = await database.OpenRawAsync();
        await using var transaction = await connection.BeginTransactionAsync();

        // 1er INSERT : accepté.
        await ExecuteAsync(connection, transaction, "INSERT INTO p4_tx_probe (code) VALUES ('A');");

        // 2e INSERT : violation d'unicité attendue.
        var duplicate = await CaptureAsync(() =>
            ExecuteAsync(connection, transaction, "INSERT INTO p4_tx_probe (code) VALUES ('A');"));

        Assert.NotNull(duplicate);
        var duplicateShape = ExceptionShape.Capture(duplicate!);
        Assert.True(duplicateShape.HasPostgresException, "B0.1 : PostgresException attendue sur le doublon.");
        Assert.Equal("23505", duplicateShape.SqlState);
        SpikeLog.Write(Experiment, Name, $"B0.1 doublon | {duplicateShape.ToEvidenceLine()}");

        // SANS rollback : toute commande suivante doit être refusée. C'est LE contrôle positif.
        var afterFailure = await CaptureAsync(() =>
            ExecuteAsync(connection, transaction, "SELECT count(*) FROM p4_tx_probe;"));

        Assert.NotNull(afterFailure);
        var abortedShape = ExceptionShape.Capture(afterFailure!);
        Assert.Equal("25P02", abortedShape.SqlState);
        SpikeLog.Write(Experiment, Name, $"B0.1 commande apres erreur SANS rollback | {abortedShape.ToEvidenceLine()}");

        // Après ROLLBACK, la même commande doit repasser.
        await transaction.RollbackAsync();

        await using (var afterRollback = connection.CreateCommand())
        {
            afterRollback.CommandText = "SELECT count(*) FROM p4_tx_probe;";
            var count = Convert.ToInt64(await afterRollback.ExecuteScalarAsync());
            Assert.Equal(0L, count); // aucune ligne 'A' persistée
            SpikeLog.Write(Experiment, Name,
                $"B0.1 apres ROLLBACK | commande acceptee=OUI | lignes persistees={count}");
        }

        SpikeLog.Write(Experiment, Name, "B0.1 = CONTROLE POSITIF VALIDE (le laboratoire voit reellement 25P02).");
    }

