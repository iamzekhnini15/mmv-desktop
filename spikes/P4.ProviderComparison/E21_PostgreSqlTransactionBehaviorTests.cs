/// <summary>
/// Intercepteur de MESURE, propre au harness (B0.4). Il n'enregistre QUE le VERBE SQL (premier
/// mot-clé), l'ordre d'exécution et le succès/échec : jamais un paramètre, jamais une valeur,
/// jamais une chaîne de connexion, jamais un message d'exception.
///
/// <para>
/// LIMITE : <c>BEGIN</c>, <c>COMMIT</c> et <c>ROLLBACK</c> transitent par l'API ADO.NET de
/// transaction (<c>DbTransaction</c>), pas par <c>DbCommand</c> ; un
/// <see cref="DbCommandInterceptor"/> ne peut donc pas les observer. Cette limite est assumée et
/// consignée : la preuve du rollback vient des DONNÉES, pas de cet intercepteur.
/// </para>
/// </summary>
internal sealed class CommandRecorder : DbCommandInterceptor
{
    private readonly object _gate = new();
    private readonly List<Entry> _entries = new();

    private string? _phase;

    public void Start(string phase)
    {
        lock (_gate)
        {
            _phase = phase;
        }
    }

    public void Stop()
    {
        lock (_gate)
        {
            _phase = null;
        }
    }

    public IReadOnlyList<string> CommandsAfterFirstFailure(string phase)
    {
        lock (_gate)
        {
            var phased = _entries.Where(e => e.Phase == phase).ToList();
            var failureIndex = phased.FindIndex(e => e.Failed);
            return failureIndex < 0
                ? Array.Empty<string>()
                : phased.Skip(failureIndex + 1).Select(e => e.Verb).ToList();
        }
    }

    public IReadOnlyList<string> WriteCommands(string phase)
    {
        lock (_gate)
        {
            return _entries
                .Where(e => e.Phase == phase)
                .Select(e => e.Verb)
                .Where(verb => verb is "INSERT" or "UPDATE" or "DELETE" or "MERGE")
                .ToList();
        }
    }

    public string Describe(string phase)
    {
        lock (_gate)
        {
            var phased = _entries
                .Where(e => e.Phase == phase)
                .Select((e, index) => $"{index + 1}.{e.Verb}{(e.Failed ? "(ECHEC)" : "(OK)")}")
                .ToList();

            return phased.Count == 0 ? "(aucune)" : string.Join(" -> ", phased);
        }
    }

    public override InterceptionResult<int> NonQueryExecuting(
        DbCommand command, CommandEventData eventData, InterceptionResult<int> result)
    {
        Record(command);
        return result;
    }

    public override ValueTask<InterceptionResult<int>> NonQueryExecutingAsync(
        DbCommand command, CommandEventData eventData, InterceptionResult<int> result,
        CancellationToken cancellationToken = default)
    {
        Record(command);
        return ValueTask.FromResult(result);
    }

    public override InterceptionResult<DbDataReader> ReaderExecuting(
        DbCommand command, CommandEventData eventData, InterceptionResult<DbDataReader> result)
    {
        Record(command);
        return result;
    }

    public override ValueTask<InterceptionResult<DbDataReader>> ReaderExecutingAsync(
        DbCommand command, CommandEventData eventData, InterceptionResult<DbDataReader> result,
        CancellationToken cancellationToken = default)
    {
        Record(command);
        return ValueTask.FromResult(result);
    }

    public override InterceptionResult<object> ScalarExecuting(
        DbCommand command, CommandEventData eventData, InterceptionResult<object> result)
    {
        Record(command);
        return result;
    }

    public override ValueTask<InterceptionResult<object>> ScalarExecutingAsync(
        DbCommand command, CommandEventData eventData, InterceptionResult<object> result,
        CancellationToken cancellationToken = default)
    {
        Record(command);
        return ValueTask.FromResult(result);
    }

    public override void CommandFailed(DbCommand command, CommandErrorEventData eventData)
        => MarkLastFailed();

    public override Task CommandFailedAsync(
        DbCommand command, CommandErrorEventData eventData, CancellationToken cancellationToken = default)
    {
        MarkLastFailed();
        return Task.CompletedTask;
    }

    private void Record(DbCommand command)
    {
        lock (_gate)
        {
            if (_phase is null)
            {
                return;
            }

            _entries.Add(new Entry(_phase, Verb(command.CommandText), false));
        }
    }

    private void MarkLastFailed()
    {
        lock (_gate)
        {
            if (_phase is null || _entries.Count == 0)
            {
                return;
            }

            _entries[^1] = _entries[^1] with { Failed = true };
        }
    }

    /// <summary>Premier mot-clé SQL uniquement — jamais le texte complet, jamais un paramètre.</summary>
    private static string Verb(string? commandText)
    {
        if (string.IsNullOrWhiteSpace(commandText))
        {
            return "(vide)";
        }

        var tokens = commandText.Split(
            new[] { ' ', '\t', '\r', '\n', '(', ';' }, StringSplitOptions.RemoveEmptyEntries);

        if (tokens.Length == 0)
        {
            return "(vide)";
        }

        var upper = tokens[0].ToUpperInvariant();
        return upper is "SELECT" or "INSERT" or "UPDATE" or "DELETE" or "MERGE"
            or "CREATE" or "DROP" or "ALTER" or "SET" or "BEGIN" or "COMMIT" or "ROLLBACK"
            ? upper
            : "(autre)";
    }

    private sealed record Entry(string Phase, string Verb, bool Failed);
}
