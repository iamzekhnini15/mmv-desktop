    /// <summary>
    /// B0.3 — Le jeton client est annulé APRÈS une écriture réussie. Le rollback doit malgré tout
    /// aboutir : c'est précisément ce que garantit le <c>CancellationToken.None</c> de
    /// <c>SafeRollbackAsync</c>. Code de production exécuté tel quel.
    /// </summary>
    [SkippableFact]
    public async Task B03_real_transaction_runner_rolls_back_after_client_cancellation()
    {
        Skip.IfNot(SpikeEnvironment.IsConfigured(Provider), SpikeEnvironment.SkipReason(Provider));

        await using var database = await SpikeDatabase.CreateAsync(Provider, "e21b03");
        SpikeLog.Section(Experiment, Name, "B0.3 — Annulation cliente APRES ecriture, via le VRAI runner");

        await ExecuteOutsideTransactionAsync(database, CreateProbeTable);

        await using var context = CreateProductionContext(database, recorder: null);
        var runner = new EfTransactionRunner(context);

        using var cts = new CancellationTokenSource();

        var thrown = await CaptureAsync(() => runner.RunAsync(async ct =>
        {
            await context.Database.ExecuteSqlRawAsync("INSERT INTO p4_tx_probe (code) VALUES ('C');", ct);

            // Le jeton est annulé APRÈS l'écriture : au moment du rollback il est déjà déclenché.
            cts.Cancel();
            throw new OperationCanceledException(cts.Token);
        }, cts.Token));

        Assert.NotNull(thrown);
        var shape = ExceptionShape.Capture(thrown!);
        SpikeLog.Write(Experiment, Name, $"B0.3 exception sortie du runner | {shape.ToEvidenceLine()}");

        // Le comportement d'annulation doit être PRÉSERVÉ : jamais transformé en erreur de persistance.
        Assert.IsNotType<PersistenceException>(thrown);
        Assert.True(shape.HasOperationCanceledException);
        Assert.True(shape.CancellationWasRequested);

        // Malgré le jeton déjà annulé, le rollback a-t-il abouti ?
        var remaining = await CountProbeAsync(database, "C");
        Assert.Equal(0L, remaining);
        SpikeLog.Write(Experiment, Name,
            $"B0.3 donnees apres annulation | lignes code='C' persistees={remaining} " +
            "=> rollback abouti MALGRE un CancellationToken deja annule (SafeRollbackAsync utilise None).");

        Assert.Null(context.Database.CurrentTransaction);
        SpikeLog.Write(Experiment, Name, "B0.3 CurrentTransaction apres sortie = null.");
    }

